"""The REAL llama adapter + manager over a real child process (#594, F3).

backend-ci cannot run the compiled ``llama-server``, so the child here is
the HTTP double (``tests/fixtures/fake_llama_embedding_server.py``) spawned
through the adapter's ``_server_command`` seam — everything else is the
production path: ``subprocess.Popen``, the log redirect, the environment
(key by ``LLAMA_API_KEY``, GPUs masked), the two-stage probe, FIFO batches,
the idle reap and the respawn of a dead child.

The vectors and the token ids the double serves are GOLDEN captures from
the real binary over the real Q8_0 GGUF
(``tests/fixtures/e5_llama_golden.json``, regenerated by
``scripts/dev/backend/capture_e5_golden.py``), so this suite holds the
transport to what the real server answered — which closes most of F2's
known limit (CI never traversed the child path): what stays out of CI is
the real binary itself and the model load, covered once per release by
``tests/test_llama_embedder_real.py`` on a dev machine and by release QA.
"""

from __future__ import annotations

import json
import os
import site
import sys
import time
from pathlib import Path

import pytest
import requests

from src.core import config
from src.core.exceptions import EngineException
from src.ingestion import embedder_child, llama_embedder
from src.ingestion.embeddings import ChildE5Embeddings

pytestmark = pytest.mark.integration

FIXTURES = Path(__file__).resolve().parent / "fixtures"
FAKE_SERVER = FIXTURES / "fake_llama_embedding_server.py"
# The double runs on the base interpreter, with this venv's packages on its
# PYTHONPATH (it imports `tokenizers`): on Windows a venv's python.exe is a
# launcher that starts the real interpreter as its own child, and terminating
# the launcher would leave that grandchild alive, holding the log file the
# reap then deletes.
_INTERPRETER = getattr(sys, "_base_executable", None) or sys.executable
_VENV_PATH = os.pathsep.join(site.getsitepackages())
GOLDEN_FILE = FIXTURES / "e5_llama_golden.json"


@pytest.fixture(scope="module")
def golden() -> dict:
    payload = json.loads(GOLDEN_FILE.read_text(encoding="utf-8"))
    return {entry["text"]: entry for entry in payload["texts"]}


@pytest.fixture
def child(monkeypatch, tmp_path):
    """The real adapter wired to spawn the double; yields the tmp root."""
    monkeypatch.setattr(config, "ROOT_DIR", tmp_path)
    gguf = tmp_path / "artifacts" / "kb-embedder" / llama_embedder.E5_GGUF_NAME
    gguf.parent.mkdir(parents=True)
    gguf.write_bytes(b"GGUF")
    monkeypatch.setenv(
        "PYTHONPATH", os.pathsep.join(filter(None, [_VENV_PATH, os.environ.get("PYTHONPATH")]))
    )
    monkeypatch.setattr(llama_embedder, "_server_command", lambda: [_INTERPRETER, str(FAKE_SERVER)])
    monkeypatch.setattr(
        llama_embedder, "_log_path", lambda port: tmp_path / f"embedder-child-{port}.log"
    )
    monkeypatch.setattr(embedder_child, "_adapter_override", llama_embedder)
    embedder_child._reset_for_tests()
    yield tmp_path
    embedder_child._reset_for_tests()


def _wait_dead(proc, timeout=10.0) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            return True
        time.sleep(0.05)
    return False


class TestRealAdapterOverTheDouble:
    def test_spawn_probe_and_the_golden_vectors(self, child, golden):
        texts = list(golden)
        vectors = embedder_child.embed_texts(texts)
        assert vectors == [golden[text]["embedding"] for text in texts]

    def test_the_log_file_captures_the_child_output(self, child):
        handle = embedder_child.ensure_embedder_running()
        log_path = Path(handle["log_path"])
        deadline = time.monotonic() + 5
        while time.monotonic() < deadline and "listening" not in log_path.read_text(
            errors="replace"
        ):
            time.sleep(0.05)
        assert "listening" in log_path.read_text(errors="replace")

    def test_only_the_keyed_backend_can_talk_to_the_child(self, child):
        handle = embedder_child.ensure_embedder_running()
        url = f"{handle['base_url']}/v1/embeddings"
        bare = requests.post(url, json={"input": ["x"]}, timeout=5)
        assert bare.status_code == 401
        wrong = requests.post(
            url,
            json={"input": ["x"]},
            headers={"Authorization": "Bearer wrong"},
            timeout=5,
        )
        assert wrong.status_code == 401
        # The manager, which holds the per-spawn key, goes through.
        assert len(embedder_child.embed_texts(["x"])[0]) > 0

    def test_an_oversized_input_fails_the_whole_batch(self, child):
        oversized = "mot " * 2000
        with pytest.raises(EngineException) as excinfo:
            embedder_child.embed_texts(["court", oversized, "aussi court"])
        assert "too large" in str(excinfo.value.message)

    def test_the_erudi_side_bound_keeps_the_path_under_the_window(self, child):
        # The SAME text that fails raw (above) succeeds through the backend,
        # because ChildE5Embeddings truncates at 510 content tokens with the
        # frozen tokenizer the server tokenizes identically to.
        oversized = "mot " * 2000
        vectors = ChildE5Embeddings().embed_documents([oversized])
        assert len(vectors) == 1
        assert ChildE5Embeddings().embed_query(oversized)

    def test_tokenize_matches_the_frozen_tokenizer_and_the_capture(self, child, golden):
        from src.ingestion.chunking import count_tokens

        handle = embedder_child.ensure_embedder_running()
        headers = {"Authorization": f"Bearer {handle['api_key']}"}
        for text, entry in golden.items():
            answer = requests.post(
                f"{handle['base_url']}/tokenize",
                json={"content": text, "add_special": True},
                headers=headers,
                timeout=5,
            )
            tokens = answer.json()["tokens"]
            # The ids the REAL binary answered at capture time...
            assert tokens == entry["tokens"]
            # ...and the frozen tokenizer's count plus BOS/EOS: the 510-token
            # client bound therefore lands under the server's 512 window.
            assert len(tokens) == count_tokens(text) + 2

    def test_the_idle_reap_terminates_the_real_process(self, child):
        handle = embedder_child.ensure_embedder_running()
        proc = handle["proc"]
        assert embedder_child.reap_if_idle(
            now=time.monotonic() + embedder_child.EMBEDDER_IDLE_SECONDS + 1
        )
        assert _wait_dead(proc)

    def test_a_killed_child_is_respawned_on_the_next_batch(self, child):
        first = embedder_child.ensure_embedder_running()
        first["proc"].kill()
        assert _wait_dead(first["proc"])
        vectors = embedder_child.embed_texts(["apres la mort"])
        assert len(vectors) == 1
        second = embedder_child.ensure_embedder_running()
        assert second["pid"] != first["pid"]

    def test_shutdown_is_terminal_and_stops_the_process(self, child):
        handle = embedder_child.ensure_embedder_running()
        embedder_child.shutdown_embedder()
        assert _wait_dead(handle["proc"])
        with pytest.raises(EngineException):
            embedder_child.ensure_embedder_running()
